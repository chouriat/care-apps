import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

const promptEntries = [
  {
    task: 'carecircle.extractPrescription',
    version: 'v1',
    promptFile: 'packages/ai-gateway/prompts/carecircle/extractPrescription.md',
  },
  {
    task: 'carecircle.summarizeVisit',
    version: 'v1',
    promptFile: 'packages/ai-gateway/prompts/carecircle/summarizeVisit.md',
  },
];

const records = promptEntries.map((entry) => {
  const fullPath = path.join(repoRoot, entry.promptFile);
  const content = fs.readFileSync(fullPath, 'utf8');
  return `  ${JSON.stringify(entry.task)}: {\n    version: ${JSON.stringify(entry.version)},\n    promptFile: ${JSON.stringify(entry.promptFile)},\n    systemPrompt: ${JSON.stringify(content)},\n  }`;
});

const rawOutput = `// Generated by scripts/sync-ai-prompts.mjs from packages/ai-gateway/prompts/carecircle/*.md.
// Do not edit by hand; run \`node scripts/sync-ai-prompts.mjs\` after updating prompt markdown files.
import type { AiTaskName } from './routes.ts';

export type CompiledPrompt = {
  version: string;
  promptFile: string;
  systemPrompt: string;
};

export const PROMPTS: Record<AiTaskName, CompiledPrompt> = {
${records.join(',\n')},
};
`;

const targetPath = path.join(repoRoot, 'supabase/carecircle/functions/ai/prompts.ts');
const prettierConfig = await prettier.resolveConfig(targetPath);
const formattedOutput = await prettier.format(rawOutput, {
  ...prettierConfig,
  filepath: targetPath,
});
fs.writeFileSync(targetPath, formattedOutput, 'utf8');
