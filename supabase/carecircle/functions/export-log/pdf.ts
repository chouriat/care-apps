import { inflateSync } from 'node:zlib';
import { PDFDocument, StandardFonts, rgb } from 'npm:pdf-lib@1.17.1';

export interface CareLogPdfEntry {
  id: string;
  createdAt: string;
  type: string;
  summary: string | null;
  actorDisplay: string;
}

export interface BuildCareLogPdfInput {
  circleName: string;
  careRecipientName: string;
  timezone: string;
  from: string;
  to: string;
  entries: ReadonlyArray<CareLogPdfEntry>;
}

export function formatTimestampInCircleZone(iso: string, timeZone: string): string {
  const d = new Date(iso);
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(d);
  const year = parts.find((p) => p.type === 'year')?.value ?? '1970';
  const month = parts.find((p) => p.type === 'month')?.value ?? '01';
  const day = parts.find((p) => p.type === 'day')?.value ?? '01';
  const hourRaw = parts.find((p) => p.type === 'hour')?.value ?? '00';
  const minute = parts.find((p) => p.type === 'minute')?.value ?? '00';
  const hour = hourRaw === '24' ? '00' : hourRaw.padStart(2, '0');
  return `${year}-${month}-${day} ${hour}:${minute}`;
}

export function formatCareLogPdfLine(entry: CareLogPdfEntry, timeZone: string): string {
  const localTime = formatTimestampInCircleZone(entry.createdAt, timeZone);
  const summary = (entry.summary ?? '').replace(/\s+/g, ' ').trim() || '-';
  const who = entry.actorDisplay.replace(/\s+/g, ' ').trim() || 'System';
  return `[ENTRY] ${localTime} | ${entry.type} | ${summary} | ${who}`;
}

/**
 * Builds a multi-page PDF document using `npm:pdf-lib@1.17.1` containing:
 * - Care recipient's name
 * - Date range (`from` to `to` in the circle's timezone)
 * - Exactly one `[ENTRY]` line per log entry (time in the circle's timezone, type, summary, who)
 */
export async function buildCareLogPdf(input: BuildCareLogPdfInput): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const pageWidth = 595.28; // A4 width pt
  const pageHeight = 841.89; // A4 height pt
  const marginX = 40;
  const topY = pageHeight - 48;
  const bottomY = 48;
  const lineHeight = 14;

  let page = pdfDoc.addPage([pageWidth, pageHeight]);
  let cursorY = topY;

  const drawLine = (text: string, isBold = false, size = 10) => {
    if (cursorY < bottomY) {
      page = pdfDoc.addPage([pageWidth, pageHeight]);
      cursorY = topY;
    }
    // WinAnsi safety: replace characters outside ASCII 32..126 with safe equivalents
    const safeText = text.replace(/[^\x20-\x7E]/g, '-');
    page.drawText(safeText, {
      x: marginX,
      y: cursorY,
      size,
      font: isBold ? boldFont : font,
      color: rgb(0.1, 0.1, 0.1),
    });
    cursorY -= lineHeight;
  };

  drawLine(`CareCircle Care Log: ${input.circleName}`, true, 14);
  cursorY -= 4;
  drawLine(`Care recipient: ${input.careRecipientName}`, true, 11);
  drawLine(`Date range: ${input.from} to ${input.to} (${input.timezone})`, false, 10);
  drawLine(`Total entries: ${input.entries.length}`, false, 10);
  cursorY -= 6;

  for (const entry of input.entries) {
    drawLine(formatCareLogPdfLine(entry, input.timezone), false, 9);
  }

  return await pdfDoc.save({ useObjectStreams: false });
}

function decodeHexPdfString(hex: string): string {
  const clean = hex.replace(/\s+/g, '');
  let out = '';
  for (let i = 0; i + 1 < clean.length; i += 2) {
    const code = Number.parseInt(clean.slice(i, i + 2), 16);
    if (Number.isFinite(code)) {
      out += String.fromCharCode(code);
    }
  }
  return out;
}

function asciiBytesToString(bytes: Uint8Array): string {
  let out = '';
  for (let i = 0; i < bytes.length; i += 1) {
    out += String.fromCharCode(bytes[i] ?? 0);
  }
  return out;
}

/**
 * Extracts drawn text lines from a PDF generated by `pdf-lib` (`buildCareLogPdf`) by
 * locating raw PDF streams, decompressing FlateDecode streams via `node:zlib`, and decoding
 * `<HEX> Tj` and `(literal) Tj` operators.
 */
export function extractTextFromPdfBytes(pdfBytes: Uint8Array): string {
  const rawIso = asciiBytesToString(pdfBytes);
  const decodedChunks: string[] = [];

  const streamRegex = /stream\r?\n([\s\S]*?)\r?\nendstream/g;
  let match: RegExpExecArray | null;
  while ((match = streamRegex.exec(rawIso)) !== null) {
    const bodyIso = match[1] ?? '';
    const compressed = new Uint8Array(bodyIso.length);
    for (let i = 0; i < bodyIso.length; i += 1) {
      compressed[i] = bodyIso.charCodeAt(i) & 0xff;
    }
    let contentText = bodyIso;
    try {
      const inflated = inflateSync(compressed);
      contentText = asciiBytesToString(new Uint8Array(inflated));
    } catch {
      // Uncompressed stream; inspect as-is.
    }

    const tjHexRegex = /<([0-9A-Fa-f\s]+)>\s*Tj/g;
    let hexMatch: RegExpExecArray | null;
    while ((hexMatch = tjHexRegex.exec(contentText)) !== null) {
      decodedChunks.push(decodeHexPdfString(hexMatch[1] ?? ''));
    }

    const tjLitRegex = /\(((?:\\.|[^\\)])*)\)\s*Tj/g;
    let litMatch: RegExpExecArray | null;
    while ((litMatch = tjLitRegex.exec(contentText)) !== null) {
      decodedChunks.push(litMatch[1] ?? '');
    }
  }

  return decodedChunks.join('\n');
}
